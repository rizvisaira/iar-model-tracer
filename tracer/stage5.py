"""Stage 5 decision rule: nearest model + per-model threshold, all fit on train only (no outliers needed).

Stage 5 full fine-tunes one inverse decoder D^-1 per model (8) instead of one per family, and scores every image with
each model's own D^-1 (scripts/run_stage5_full.sh). The rule extends the paper's per-model test (Zhao et al., App. T)
to the 8 models:

1. Each model m has one provenance score s_m (lower = more likely generated by m): its family's Stage 2 score (RAR
   quant, VAR cal) computed with m's own D^-1. It is standardised as z_m = (log s_m - mu_m) / sd_m using the train
   images of model m.
2. Label = argmin_m z_m. If that z exceeds tau_m, the q-quantile of z_m over model m's own train images, the image is
   an outlier (it is not typical of any known model).

There is no separate size step: the nearest model is the label. NearestFamilyThreshold (tracer/stage1.py) is unchanged.

Usage:
    feats = load_model_features(CACHE / "stage5full" / "features", ckpts)  # columns <model>_<signal>
    model = NearestModelThreshold(model_score_cols(), q=0.95).fit(train)
    labels = model.predict(df)  # one of the 9 label strings per row
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

from .common import FAMILY_OF, LABELS, build_index

KNOWN_MODELS = [l for l in LABELS if l != "outlier"]
SIGNAL = {"rar": "quant", "var": "cal"}  # Stage 2's selected score per family
META = ["key", "split", "label", "family", "name"]


def model_score_cols(signal: dict = SIGNAL, models=KNOWN_MODELS) -> dict:
    """{model: "<model>_<its family's signal>"}, e.g. {"var16": "var16_cal", ..., "rarb": "rarb_quant"}."""
    return {m: f"{m}_{signal[FAMILY_OF[m]]}" for m in models}


def load_model_features(root, ckpts: dict = None, models=KNOWN_MODELS, limit: int = None) -> pd.DataFrame:
    """Join the per-model tables <root>/<model>/<family>.csv (scripts/extract_features.py --out <root>/<model>).

    Each table's signal columns <family>_<signal> are renamed <model>_<signal>; key, split, label, family and name
    are kept once. Every table must have the rows of build_index(), in order (with limit, its first limit rows, as
    written by extract_features.py --limit). With ckpts ({model: checkpoint path}), also asserts that each table was
    computed with that checkpoint and --var-iters 0.
    """
    root, keys, out = Path(root), build_index().key.tolist()[:limit], None
    for m in models:
        fam = FAMILY_OF[m]
        if ckpts is not None:
            cfg = json.loads((root / m / fam / "config.json").read_text())
            assert cfg.get("inv_ckpt") == str(ckpts[m]) and cfg["var_iters"] == 0, f"{m}: {cfg}"
        df = pd.read_csv(root / m / f"{fam}.csv")
        assert df.key.tolist() == keys, f"{m}: rows differ from build_index()"
        df = df.rename(columns={c: f"{m}_{c[len(fam) + 1:]}" for c in df.columns if c.startswith(fam + "_")})
        out = df if out is None else out.merge(df.drop(columns=META[1:]), on="key", validate="1:1")
    return out


def _log(x) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    assert (x > 0).all(), "scores must be positive (and not NaN)"
    return np.log(x)


class NearestModelThreshold:
    """Nearest-model classifier with a per-model outlier threshold.

    score_cols: model -> loss column (lower = more likely that model). Its order breaks exact ties (first wins).
    q: quantile of the model's own train z-scores used as the outlier threshold tau.

    Fitted attributes, keyed by model: mu_, sd_ (mean / population std of the log score), tau_.
    Input frames need the score columns, plus `label` for fit.
    """

    def __init__(self, score_cols: dict, q: float = 0.95):
        self.score_cols = dict(score_cols)  # e.g. model_score_cols()
        self.q = q

    def fit(self, train: pd.DataFrame):
        """Fit mu_, sd_, tau_ per model on its own train images. Train must have no outliers."""
        assert train.label.notna().all() and set(train.label) <= set(KNOWN_MODELS), "train: known models only"
        self.mu_, self.sd_, self.tau_ = {}, {}, {}
        for m, col in self.score_cols.items():
            s = _log(train.loc[train.label == m, col])
            assert len(s) >= 2, f"{m}: needs at least 2 train images"
            self.mu_[m], self.sd_[m] = s.mean(), s.std()
            # outlier threshold: q-quantile of the model's own train z-scores
            self.tau_[m] = np.quantile((s - self.mu_[m]) / self.sd_[m], self.q)
        return self

    def model_z(self, df: pd.DataFrame) -> pd.DataFrame:
        """Columns z_<model>: z_m = (log s_m - mu_m) / sd_m for every row (lower = more typical of m)."""
        return pd.DataFrame({f"z_{m}": (_log(df[c]) - self.mu_[m]) / self.sd_[m] for m, c in self.score_cols.items()},
                            index=df.index)

    def nearest(self, df: pd.DataFrame) -> pd.DataFrame:
        """Columns model (argmin_m z_m, before the outlier check), z (its z) and tau (its threshold)."""
        z = self.model_z(df).values
        i = z.argmin(axis=1)  # first minimum, so ties follow score_cols order
        models = np.array(list(self.score_cols))[i]
        return pd.DataFrame({"model": models, "z": z[np.arange(len(z)), i],
                             "tau": [self.tau_[m] for m in models]}, index=df.index)

    def predict(self, df: pd.DataFrame) -> pd.Series:
        """Full label per row (one of LABELS): the nearest model, or "outlier" if its z exceeds its tau."""
        n = self.nearest(df)
        return n.model.where(n.z <= n.tau, "outlier")

    def predict_family(self, df: pd.DataFrame) -> pd.Series:
        """Per row: "rar", "var" or "outlier", the family of predict()."""
        return self.predict(df).map(FAMILY_OF)
